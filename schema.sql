PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS episodes (
    episode_number INTEGER PRIMARY KEY,
    ranking_label TEXT NOT NULL,
    ranking_month TEXT,
    stats_start_date TEXT NOT NULL,
    youtube_post_date TEXT NOT NULL,
    youtube_url TEXT NOT NULL,
    instagram_url TEXT
);

CREATE TABLE IF NOT EXISTS teams (
club TEXT PRIMARY KEY NOT NULL
);

CREATE TABLE IF NOT EXISTS rankings (
    episode_number INTEGER NOT NULL REFERENCES episodes(episode_number),
    host TEXT NOT NULL,
    rank_position INTEGER NOT NULL CHECK (rank_position BETWEEN 1 AND 10),
    club TEXT NOT NULL REFERENCES teams(club),
    PRIMARY KEY (episode_number, host, rank_position)
);

CREATE TABLE IF NOT EXISTS matches (
    match_id INTEGER PRIMARY KEY,
    match_date TEXT NOT NULL,
    club TEXT NOT NULL REFERENCES teams(club),
    opponent TEXT NOT NULL,
    competition TEXT NOT NULL,
    result TEXT NOT NULL CHECK (result IN ('W', 'D', 'L')),
    opponent_elo REAL
);

CREATE TABLE IF NOT EXISTS change_requests (
number INTEGER PRIMARY KEY AUTOINCREMENT,
    record_id TEXT NOT NULL,
    new_value TEXT NOT NULL,
    source_url TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting', 'approved', 'rejected'))
);

